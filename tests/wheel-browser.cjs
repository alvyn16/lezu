async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 980, height: 760 });
  await page.reload();
  await page.evaluate(() => window.scrollTo(0, 0));
  const shelf = page.locator('.cover-shelf');
  await shelf.waitFor();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForFunction(() => scrollY === 0);
  const box = await shelf.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 80);
  await page.mouse.wheel(0, 120);
  await page.waitForFunction(() => document.querySelector('.cover-shelf').scrollLeft > 50);
  const forward = await shelf.evaluate(el => el.scrollLeft);
  const pageY = await page.evaluate(() => scrollY);
  if (pageY !== 0) throw Error(`Wheel moved the page instead of the shelf (${JSON.stringify({ pageY, forward, box })})`);
  await page.mouse.wheel(0, -60);
  await page.waitForFunction(previous => document.querySelector('.cover-shelf').scrollLeft < previous, forward);
  const reverse = await shelf.evaluate(el => el.scrollLeft);
  await page.mouse.wheel(80, 0);
  await page.waitForFunction(previous => document.querySelector('.cover-shelf').scrollLeft > previous, reverse);
  const eventChecks = await shelf.evaluate(el => {
    el.scrollLeft = 100;
    const zoom = new WheelEvent('wheel', { deltaY: 100, ctrlKey: true, bubbles: true, cancelable: true });
    el.dispatchEvent(zoom);
    const zoomPreserved = !zoom.defaultPrevented && el.scrollLeft === 100;
    const lines = new WheelEvent('wheel', { deltaY: 3, deltaMode: 1, bubbles: true, cancelable: true });
    el.dispatchEvent(lines);
    const linesMoved = lines.defaultPrevented && el.scrollLeft > 100;
    const pages = new WheelEvent('wheel', { deltaY: 1, deltaMode: 2, bubbles: true, cancelable: true });
    el.dispatchEvent(pages);
    const endReached = el.scrollLeft >= el.scrollWidth - el.clientWidth - 1;
    const edge = new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true });
    el.dispatchEvent(edge);
    return { zoomPreserved, linesMoved, endReached, edgeReleased: !edge.defaultPrevented, scrollbarHidden: getComputedStyle(el).scrollbarWidth === 'none' };
  });
  if (Object.values(eventChecks).some(passed => !passed)) throw Error(JSON.stringify(eventChecks));
  await page.mouse.wheel(0, 100);
  await page.waitForFunction(() => scrollY > 0);
  await page.reload();
  await page.mouse.move(230, 60);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.mouse.wheel(0, 100);
  await page.waitForFunction(() => scrollY > 0);
  await page.reload();
  await page.getByRole('button', { name: 'See All', exact: true }).click();
  const libraryBox = await shelf.boundingBox();
  await page.mouse.move(libraryBox.x + 120, libraryBox.y + 60);
  await page.mouse.wheel(0, 100);
  await page.waitForFunction(() => document.querySelector('.cover-shelf').scrollLeft > 0);
  await page.locator('.sidebar [data-nav="steam"]').click();
  const updatedBox = await shelf.boundingBox();
  await page.mouse.move(updatedBox.x + 120, updatedBox.y + 60);
  await page.mouse.wheel(0, 100);
  await page.waitForFunction(() => document.querySelector('.cover-shelf').scrollLeft > 0);
  await page.reload();
  await page.getByRole('button', { name: 'View Balatro', exact: true }).focus();
  const keyboardBox = await page.getByRole('button', { name: 'View Balatro', exact: true }).boundingBox();
  if (keyboardBox.x + keyboardBox.width > 980) throw Error('Keyboard reveal regressed');
  await page.setViewportSize({ width: 1920, height: 1080 });
  const noOverflow = await shelf.evaluate(el => {
    const wheel = new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true });
    el.dispatchEvent(wheel);
    return el.scrollWidth <= el.clientWidth && !wheel.defaultPrevented;
  });
  if (!noOverflow) throw Error('Non-overflowing shelf consumed the wheel');
  await page.setViewportSize({ width: 980, height: 760 });
  if (errors.length) throw Error(errors.join('\n'));
  await page.mouse.move(0, 0);
  await page.screenshot({ path: 'docs/screenshots/home-wheel.png' });
  return { forward: 'passed', reverse: 'passed', trackpad: 'passed', ...eventChecks, outsideShelf: 'passed', library: 'passed', afterFilter: 'passed', keyboard: 'passed', noOverflow, errors };
}
